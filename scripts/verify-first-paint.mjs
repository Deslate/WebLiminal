import { chromium } from '@playwright/test';
import { writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 960 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (['warning', 'error'].includes(m.type())) errors.push(m.text()); });
// Intentionally slow the application module. The HTML image must already be present.
await page.route('**/assets/*.js', async route => { await new Promise(resolve => setTimeout(resolve, 1800)); await route.continue(); });
await page.goto('http://127.0.0.1:4174/poolrooms/', { waitUntil: 'commit' });
await page.waitForFunction(() => document.querySelector('#first-frame img')?.complete && document.querySelector('#first-frame img')?.naturalWidth > 0);
const poster = await page.evaluate(() => ({ imageLoaded: document.querySelector('#first-frame img').naturalWidth > 0, canvasHidden: getComputedStyle(document.querySelector('#experience')).visibility === 'hidden', appLoaded: !!window.__POOLROOMS__, time: performance.now() }));
assert(poster.imageLoaded && poster.canvasHidden && !poster.appLoaded);
await page.screenshot({ path: 'docs/verification/first-paint-delayed-js.jpg', type: 'jpeg', quality: 85 });
await page.waitForFunction(() => window.__POOLROOMS__?.snapshot().firstFrameMs != null);
const ready = await page.evaluate(() => ({ firstFrameMs: window.__POOLROOMS__.snapshot().firstFrameMs, paints: performance.getEntriesByType('paint').map(p=>({name:p.name,time:p.startTime})), canvasVisible: getComputedStyle(document.querySelector('#experience')).visibility === 'visible' }));
assert(ready.canvasVisible); assert.equal(errors.length, 0);
const report={artificialModuleDelayMs:1800,poster,ready,errors};
writeFileSync('docs/verification/first-paint.json',JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
await browser.close();
